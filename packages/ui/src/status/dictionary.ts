const BY_ID = new Map(STATUS_DICTIONARY.map((e) => [e.id, e]));

/** An entry of the dictionary; a state that is not in it does not exist (DS-23 FR 2), so an unknown id throws. */
export function statusEntry(id: string): StatusEntry {
  const entry = BY_ID.get(id);
  if (!entry) throw new RangeError(`«${id}» is not in the status dictionary (DS-23@PoC FR 2)`);
  return entry;
}
