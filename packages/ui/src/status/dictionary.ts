import type { MessageKey } from "@willowsum/i18n";

/** The five fixed tones of a status (DS-23@PoC FR 3). */
export type StatusTone = "positive" | "attention" | "negative" | "info" | "neutral";

/** The text colour token of the mark and the word (never the fill of a bar: that is `usage-*` / `over-*`). */
export type StatusInk =
  | "gain"
  | "gain-soft"
  | "on-warning"
  | "loss"
  | "loss-soft"
  | "link"
  | "brand"
  | "ink-muted"
  | "disabled-ink";

export interface StatusEntry {
  /** `<family>.<state>`: the family letters of DS-23 (a, b, v, g, d, e, e1, f, zh, z2, i, yi, k). */
  id: string;
  family: string;
  tone: StatusTone;
  ink: StatusInk;
  /**
   * The marker shown before the word: «•», «✓», «!», «✕», «i», an arrow «▲» / «▼» («▲▼»: the direction comes
   * from the data), «—», «–», «№» (the number of a step). An empty marker is allowed only where the word is
   * itself the sign (a title, a count line, a plan label); `NO_MARKER` lists them.
   */
  marker: string;
  /** A badge: a flat plate on the tone's tint (CMP-18); otherwise the text sits on the surface. */
  plate: boolean;
  /** «нейтральний (тихий)»: the plate on `surface-300` with `ink-muted`, no tint. */
  quiet: boolean;
  textKey: MessageKey;
  /** The requirements that set the rule (DS-23 «Джерело»). */
  sources: readonly string[];
  /** The abbreviated word (`дн.`, `міс.`) is spoken in full, with a plural form (`<textKey>.spoken.<form>`). */
  spoken?: "days" | "months";
}

/** A family of states (DS-23 «Словник»). */
export interface StatusFamily {
  id: string;
  titleKey: MessageKey;
}

