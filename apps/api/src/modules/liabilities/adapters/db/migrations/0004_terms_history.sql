-- The dated history of a liability's terms (FIN-12@PoC FR 4, AC10; #244 item 7): a loan's rate and monthly payment and a
-- credit card's limit changed in «Реквізити» apply from the date of the change. `liabilities` keeps the terms in effect
-- now (as before, so the previous code reads and writes it unchanged — ARC-03 FR 4, expand only); this table keeps what
-- was in effect before, one row per period:
--   - `valid_from` NULL — the terms the liability had from its registration until the first change (written by that
--     change, so a liability never changed has no rows and its terms are those of `liabilities`);
--   - `valid_from` a date — the terms from that day on, until the next row's date; several changes on one day are in
--     `seq` order, the last one wins.
-- Rows are only added (the history of a change is never rewritten). The terms columns follow `liabilities`' rules.
-- Row-level security on household_id is added by the migration runner (ARC-03 FR 2); erasing a space deletes its rows
-- (a cascade from `liabilities`, as the previous code's erasure deletes only that table).
CREATE TABLE liability_terms (
  household_id uuid NOT NULL,
  id uuid NOT NULL,
  liability_id uuid NOT NULL,
  -- BY DEFAULT, so a restore can load the copied values (NFR-16 FR 9).
  seq bigint GENERATED BY DEFAULT AS IDENTITY,
  valid_from date,
  kind text NOT NULL CHECK (kind IN ('loan', 'credit-card')),
  currency text NOT NULL CHECK (currency ~ '^[A-Z][A-Z0-9]{2,9}$'),
  annual_rate numeric(38, 18) CHECK (annual_rate BETWEEN 0 AND 100 AND annual_rate = round(annual_rate, 2)),
  monthly_payment numeric(38, 18) CHECK (monthly_payment > 0),
  credit_limit numeric(38, 18) CHECK (credit_limit >= 0),
  grace_period_days integer CHECK (grace_period_days BETWEEN 0 AND 365),
  created_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (household_id, id),
  CHECK (kind <> 'loan' OR grace_period_days IS NULL),
  CHECK (kind <> 'credit-card' OR monthly_payment IS NULL),
  FOREIGN KEY (household_id, liability_id) REFERENCES liabilities (household_id, id) ON DELETE CASCADE
    DEFERRABLE INITIALLY DEFERRED
);
-- At most one «since the registration» row per liability.
CREATE UNIQUE INDEX liability_terms_initial ON liability_terms (household_id, liability_id) WHERE valid_from IS NULL;
CREATE INDEX liability_terms_by_liability ON liability_terms (household_id, liability_id, valid_from, seq);
