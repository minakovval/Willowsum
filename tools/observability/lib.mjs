// Generator and checks of the SLO and alert rules (ARC-09 FR 4, NFR-10 FR 5–6, ADR-0006). Zero dependencies.

const HEADER = (what) =>
  `# Generated by tools/observability (ARC-09, NFR-10, ADR-0006) — do not edit; change tools/observability/definitions.mjs\n` +
  `# and run: node tools/observability/index.mjs --write\n# ${what}\n`;

/** `30s`, `2m`, `1h`, `3d` → seconds; NaN for anything else. */
export function durationSeconds(text) {
  const m = /^([0-9]+)(s|m|h|d)$/.exec(String(text));
  if (!m) return Number.NaN;
  return Number(m[1]) * { s: 1, m: 60, h: 3600, d: 86400 }[m[2]];
}

const seconds = (s) => (s % 3600 === 0 ? `${s / 3600}h` : s % 60 === 0 ? `${s / 60}m` : `${s}s`);

/**
 * A small YAML writer for maps, lists, strings, numbers and booleans. Strings are JSON-quoted (a JSON string is
 * a valid YAML double-quoted scalar), keys are plain identifiers, so the output parses the same everywhere.
 */
export function toYaml(value, indent = 0) {
  const pad = " ".repeat(indent);
  const scalar = (v) => (typeof v === "string" ? JSON.stringify(v) : String(v));
  const isScalar = (v) => v === null || typeof v !== "object";
  if (Array.isArray(value)) {
    if (value.length === 0) return `${pad}[]\n`;
    return value
      .map((item) => {
        if (isScalar(item)) return `${pad}- ${scalar(item)}\n`;
        const inner = toYaml(item, indent + 2);
        return `${pad}- ${inner.slice(indent + 2)}`;
      })
      .join("");
  }
  return Object.entries(value)
    .filter(([, v]) => v !== undefined)
    .map(([k, v]) => {
      if (!/^[A-Za-z_][A-Za-z0-9_]*$/.test(k)) throw new Error(`YAML key «${k}» is not a plain identifier`);
      if (isScalar(v)) return `${pad}${k}: ${scalar(v)}\n`;
      if (Array.isArray(v) && v.length === 0) return `${pad}${k}: []\n`;
      if (!Array.isArray(v) && Object.keys(v).length === 0) return `${pad}${k}: {}\n`;
      return `${pad}${k}:\n${toYaml(v, indent + 2)}`;
    })
    .join("");
}

/** Prometheus / Mimir rule groups (importable with mimirtool or Grafana's data-source-managed rules). */
export function ruleGroups(defs) {
  const interval = seconds(defs.TIMING.evaluationIntervalS);
  return {
    groups: [
      { name: "willowsum-slo-recording", interval, rules: defs.RECORDING_RULES.map((r) => ({ ...r })) },
      {
        name: "willowsum-slo-alerts",
        interval,
        rules: defs.ALERTS.map((a) => ({
          alert: a.alert,
          expr: a.expr,
          for: a.for,
          labels: { severity: a.severity, slo: a.slo, service: "willowsum-api" },
          annotations: {
            summary: a.summary,
            requirement: a.requirement,
            runbook: `infra/observability/README.md#${a.alert.toLowerCase()}`,
          },
        })),
      },
    ],
  };
}

/** Alertmanager routing: pages to the on-call receiver, tickets to the ticket receiver. */
export function alertmanagerConfig(defs) {
  return {
    route: {
      receiver: "on-call",
      group_by: ["alertname", "slo"],
      group_wait: seconds(defs.TIMING.groupWaitS),
      group_interval: seconds(defs.TIMING.groupIntervalS),
      repeat_interval: seconds(defs.TIMING.repeatIntervalS),
      routes: [{ receiver: "ticket", matchers: ['severity="ticket"'], group_wait: "5m" }],
    },
    // The contact points (who is on call, and how) are set in Grafana Cloud with their secrets, not here.
    receivers: [{ name: "on-call" }, { name: "ticket" }],
  };
}

/** A Grafana dashboard of the SLOs (NFR-10 FR 5). */
export function dashboard(defs) {
  const datasource = { type: "prometheus", uid: "${datasource}" };
  return {
    uid: "willowsum-slo",
    title: "Willowsum API — SLO",
    tags: ["willowsum", "slo", "ARC-09", "NFR-10"],
    timezone: "utc",
    schemaVersion: 39,
    time: { from: "now-24h", to: "now" },
    templating: {
      list: [{ name: "datasource", type: "datasource", query: "prometheus", label: "Data source" }],
    },
    panels: defs.DASHBOARD_PANELS.map((p, i) => ({
      id: i + 1,
      title: p.title,
      type: p.type,
      datasource,
      gridPos: { h: 8, w: p.type === "stat" ? 6 : 12, x: (i % 2) * 12, y: Math.floor(i / 2) * 8 },
      fieldConfig: { defaults: { unit: p.unit }, overrides: [] },
      targets: [{ refId: "A", datasource, expr: p.expr }],
    })),
  };
}

export function generate(defs) {
  return {
    "rules.yaml": HEADER("Rule groups for the Grafana Cloud (Mimir) ruler") + toYaml(ruleGroups(defs)),
    "alertmanager.yaml":
      HEADER("Alert routing; receivers' contact points live in Grafana Cloud") + toYaml(alertmanagerConfig(defs)),
    "dashboard-slo.json": `${JSON.stringify(dashboard(defs), null, 2)}\n`,
  };
}

function balanced(expr) {
  const pairs = { ")": "(", "]": "[", "}": "{" };
  const stack = [];
  let quoted = false;
  for (const c of expr) {
    if (c === '"') quoted = !quoted;
    if (quoted) continue;
    if ("([{".includes(c)) stack.push(c);
    else if (c in pairs && stack.pop() !== pairs[c]) return false;
  }
  return stack.length === 0 && !quoted;
}

/** Series names an expression reads (identifiers followed by `{`, `[` or used bare), minus PromQL words. */
const PROMQL_WORDS = new Set(
  "sum rate increase histogram_quantile by le and or unless without on ignoring group_left group_right bool".split(" "),
);
export function seriesIn(expr) {
  const out = new Set();
  const stripped = expr.replace(/"[^"]*"/g, '""').replace(/\{[^}]*\}/g, "{}").replace(/\[[^\]]*\]/g, "[]");
  for (const m of stripped.matchAll(/[A-Za-z_:][A-Za-z0-9_:]*/g)) {
    const name = m[0];
    const next = stripped[m.index + name.length];
    if (PROMQL_WORDS.has(name) || next === "(") continue;
    out.add(name);
  }
  return out;
}

/** Problems of the definitions; empty means the rules are valid. */
export function validate(defs) {
  const problems = [];
  const { TIMING } = defs;
  const known = new Set();
  for (const name of Object.values(defs.METRICS)) {
    known.add(name);
    if (name.endsWith("_seconds")) for (const s of ["_bucket", "_count", "_sum"]) known.add(name + s);
  }
  const records = new Set();
  for (const r of defs.RECORDING_RULES) {
    if (!/^[a-z_]+:[a-z0-9_]+:[a-z0-9_]+$/.test(r.record)) problems.push(`recording rule ${r.record}: name is level:metric:operation`);
    if (records.has(r.record)) problems.push(`recording rule ${r.record}: declared twice`);
    records.add(r.record);
  }
  const check = (where, expr, names) => {
    if (typeof expr !== "string" || expr.trim() === "") problems.push(`${where}: empty expression`);
    else if (!balanced(expr)) problems.push(`${where}: unbalanced brackets or quotes`);
    else for (const s of seriesIn(expr)) if (!names.has(s) && !/^[0-9.]+$/.test(s)) problems.push(`${where}: unknown series ${s}`);
  };
  for (const r of defs.RECORDING_RULES) check(`recording rule ${r.record}`, r.expr, known);
  const readable = new Set([...known, ...records]);
  const alerts = new Set();
  const slos = new Set(defs.SLOS.map((s) => s.id));
  for (const a of defs.ALERTS) {
    const where = `alert ${a.alert}`;
    if (!/^[A-Z][A-Za-z0-9]+$/.test(a.alert)) problems.push(`${where}: name is UpperCamelCase`);
    if (alerts.has(a.alert)) problems.push(`${where}: declared twice`);
    alerts.add(a.alert);
    check(where, a.expr, readable);
    if (!["page", "ticket"].includes(a.severity)) problems.push(`${where}: severity is page or ticket`);
    if (!slos.has(a.slo)) problems.push(`${where}: unknown SLO ${a.slo}`);
    if (!a.summary || !a.requirement) problems.push(`${where}: needs a summary and the requirement it covers`);
    const forS = durationSeconds(a.for);
    if (Number.isNaN(forS)) problems.push(`${where}: for «${a.for}» is not a duration`);
    if (a.severity === "page") {
      const delay = alertDelaySeconds(TIMING, forS);
      if (!(delay <= TIMING.maxAlertDelayS))
        problems.push(`${where}: worst-case delay ${delay} s exceeds ${TIMING.maxAlertDelayS} s (NFR-10 FR 6)`);
    }
  }
  for (const clause of defs.REQUIRED_ALERTS)
    if (!defs.ALERTS.some((a) => a.requirement === clause && a.severity === "page"))
      problems.push(`required alert missing (paging): ${clause}`);
  for (const p of defs.DASHBOARD_PANELS) check(`panel «${p.title}»`, p.expr, readable);
  return problems;
}

/** Worst case from «the condition holds in the process» to «the on-call person is notified», in seconds. */
export function alertDelaySeconds(timing, forS) {
  return 2 * timing.metricExportIntervalS + timing.evaluationIntervalS + forS + timing.groupWaitS;
}
