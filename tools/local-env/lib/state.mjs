// Local credentials for the local environment (CICD-04, CICD-12).
//
// Secrets are created by the machine, never by a person and never committed: on the first run the tool
// writes cryptographically random values (≥ 32 bytes for passwords and secret keys) into
// infra/local/.state/ (git-ignored, directory 0700, file 0600). Later runs reuse them, so the
// database volume keeps working. Values are local-only and guard synthetic data.
import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';

export const ENV_FILE = 'local.env';

/** Names of the generated secret variables; never printed by the tool. */
export const SECRET_KEYS = [
  'WS_LOCAL_PG_PASSWORD',
  'WS_LOCAL_SMTP_PASSWORD',
  'WS_LOCAL_MAIL_UI_PASSWORD',
  'WS_LOCAL_S3_SECRET_KEY',
];

/** Non-secret defaults. Ports can be overridden by editing the generated env file. */
const DEFAULTS = {
  WS_LOCAL_PG_USER: 'willowsum',
  WS_LOCAL_PG_DB: 'willowsum',
  WS_LOCAL_PG_PORT: '5432',
  WS_LOCAL_SMTP_USER: 'willowsum',
  WS_LOCAL_SMTP_PORT: '1025',
  WS_LOCAL_MAIL_UI_USER: 'willowsum',
  WS_LOCAL_MAIL_UI_PORT: '8025',
  WS_LOCAL_S3_PORT: '8333',
  WS_LOCAL_S3_REGION: 'eu-local-1',
  WS_LOCAL_S3_BUCKET: 'willowsum-files',
};

const random = (bytes) => crypto.randomBytes(bytes).toString('base64url');

function generate() {
  return {
    ...DEFAULTS,
    WS_LOCAL_PG_PASSWORD: random(32),
    WS_LOCAL_SMTP_PASSWORD: random(32),
    WS_LOCAL_MAIL_UI_PASSWORD: random(32),
    // The access key is an identifier, the secret key is the secret.
    WS_LOCAL_S3_ACCESS_KEY: `WSLOCAL${crypto.randomBytes(8).toString('hex').toUpperCase()}`,
    WS_LOCAL_S3_SECRET_KEY: random(32),
  };
}

export function parseEnv(text) {
  const values = {};
  for (const line of text.split('\n')) {
    const m = /^([A-Z0-9_]+)=(.*)$/.exec(line.trim());
    if (m) values[m[1]] = m[2];
  }
  return values;
}

function formatEnv(values) {
  const lines = [
    '# Generated by tools/local-env (CICD-04). Local machine only; git-ignored; do not share or commit.',
    '# Delete this directory and run `pnpm local:reset` to get new credentials.',
    ...Object.entries(values).map(([k, v]) => `${k}=${v}`),
  ];
  return `${lines.join('\n')}\n`;
}

/**
 * Writes a new file created with mode 0600 and renames it over the target, so secrets are never
 * written into a file with looser permissions (an existing file's mode is not trusted).
 */
function writePrivate(file, content) {
  const tmp = `${file}.${process.pid}.tmp`;
  fs.rmSync(tmp, { force: true });
  fs.writeFileSync(tmp, content, { mode: 0o600, flag: 'wx' });
  fs.chmodSync(tmp, 0o600);
  fs.renameSync(tmp, file);
}

/**
 * Creates the state directory on first use and returns the local values. Existing values are kept;
 * keys missing from an older env file are added.
 */
export function ensureState(stateDir) {
  fs.mkdirSync(stateDir, { recursive: true, mode: 0o700 });
  fs.chmodSync(stateDir, 0o700);
  const envPath = path.join(stateDir, ENV_FILE);
  const existing = fs.existsSync(envPath) ? parseEnv(fs.readFileSync(envPath, 'utf8')) : {};
  const values = { ...generate(), ...existing };
  const created = Object.keys(existing).length === 0;
  if (created || Object.keys(values).some((k) => !(k in existing))) writePrivate(envPath, formatEnv(values));
  else fs.chmodSync(envPath, 0o600); // tighten a file whose mode was loosened by hand
  return { values, envPath, created };
}

/** Reads existing state without creating it; null when the stack was never started. */
export function readState(stateDir) {
  const envPath = path.join(stateDir, ENV_FILE);
  if (!fs.existsSync(envPath)) return null;
  return { values: parseEnv(fs.readFileSync(envPath, 'utf8')), envPath };
}
