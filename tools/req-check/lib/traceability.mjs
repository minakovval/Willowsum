// Generates docs/traceability/: matrix.md, release-<key>.md per release, coverage.md, README.md.
// Output is deterministic (no dates) so CI can regenerate it and fail on any difference.
import { SLICE_RELEASES, RELEASE_KEY, releaseIndex } from './config.mjs';

const esc = (s) => String(s).replace(/\|/g, '\\|').replace(/\r?\n/g, ' ');
const list = (xs) => (xs.length ? xs.map(esc).join(', ') : '—');
const HEADER = (cmd) => `Generated by \`${cmd}\` (tools/req-check) from the link headers of the requirement slices. Do not edit by hand.`;
const CMD = 'node tools/req-check/index.mjs --traceability';

/** Sort slices by requirement ID (area, number, suffix) and release. */
function bySid(a, b) {
  return a.id < b.id ? -1 : a.id > b.id ? 1 : releaseIndex(a.release) - releaseIndex(b.release);
}

/**
 * Relative link from docs/traceability/ to a file in the requirements folder.
 * @param {string} rel repository-relative path (docs/requirements/bud/BUD-16.poc.md)
 * @param {string} outDir repository-relative output dir (docs/traceability)
 */
function relLink(rel, outDir) {
  const up = outDir.split('/').filter(Boolean).map(() => '..');
  return [...up, rel].join('/');
}

const sliceLink = (s, outDir) => `[${s.sid}](${relLink(s.doc.rel, outDir)})`;
const state = (s) => (s.explicit ? 'мігровано' : 'не мігровано');

/**
 * Build waves (Kahn levels) for the slices of one release. Dependencies on earlier releases are
 * already built. Returns waves of slice IDs and any slices left in a cycle.
 */
export function buildWaves(nodes, model) {
  const inRelease = new Set(nodes);
  const deps = new Map(nodes.map((sid) => [sid, (model.slices.get(sid)?.links.depends ?? []).filter((t) => inRelease.has(t))]));
  const done = new Set();
  const waves = [];
  while (done.size < nodes.length) {
    const wave = nodes.filter((sid) => !done.has(sid) && deps.get(sid).every((t) => done.has(t))).sort();
    if (!wave.length) break;
    for (const sid of wave) done.add(sid);
    waves.push(wave);
  }
  return { waves, cyclic: nodes.filter((sid) => !done.has(sid)).sort() };
}

const nodeId = (sid) => sid.replace(/[^A-Za-z0-9]/g, '_');

/**
 * @param {ReturnType<import('./model.mjs').buildModel>} model
 * @param {import('./registries.mjs').Registries} registries
 * @param {string} [outDir]
 * @returns {Map<string, string>} file name → content
 */
export function renderTraceability(model, registries, outDir = 'docs/traceability') {
  const files = new Map();
  const all = [...model.slices.values()].sort(bySid);
  const explicit = all.filter((s) => s.explicit);
  const migrated = [...model.features.values()].filter((f) => f.card);

  // README.
  files.set(
    'README.md',
    [
      '# Traceability',
      '',
      HEADER(CMD),
      '',
      'Every requirement is split into release slices (`BUD-16@PoC`, `BUD-16@PoC v2` …). A migrated requirement has a card (`bud/BUD-16.md`) and one slice file per release (`bud/BUD-16.poc.md`); its links live in the «Зв\'язки» header of each slice. When the card is a source (it has a «## Джерело зрізів» part with release tags), its slice files are views generated by `node tools/req-check/index.mjs --views`; links below point at the views. A requirement that is not migrated yet counts as one implicit slice per release on its «Реліз» line, without links.',
      '',
      `Status: ${migrated.length} migrated requirements with ${explicit.length} slice files; ${model.features.size - migrated.length} requirements not migrated (${all.length - explicit.length} implicit slices).`,
      '',
      '| File | Contents |',
      '| --- | --- |',
      '| [matrix.md](matrix.md) | One row per slice: release, module, dependencies, design, shared rules, use cases, tests |',
      ...SLICE_RELEASES.map((r) => `| [release-${RELEASE_KEY[r]}.md](release-${RELEASE_KEY[r]}.md) | ${r}: slices, dependency graph, build sequence in waves |`),
      '| [coverage.md](coverage.md) | Per release: screens without a slice, slices without design, slices without acceptance criteria |',
      '',
    ].join('\n'),
  );

  // Matrix.
  const M = ['# Traceability matrix', '', HEADER(CMD), '', `${all.length} slices: ${explicit.length} migrated, ${all.length - explicit.length} not migrated (links unknown until the requirement is migrated).`, ''];
  M.push('| Slice | Release | State | Module | Extends | Depends on | Design | Shared rules | Use cases | Tests | Criteria |');
  M.push('| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | ---: |');
  for (const s of all) {
    const L = s.links;
    M.push(`| ${sliceLink(s, outDir)} | ${s.release} | ${state(s)} | ${list(L.modules)} | ${list(L.extends)} | ${list(L.depends)} | ${list(L.design)} | ${list(L.shared)} | ${list(L.useCases)} | ${list(L.tests)} | ${s.criteria} |`);
  }
  M.push('');
  files.set('matrix.md', M.join('\n'));

  // Per release.
  for (const r of SLICE_RELEASES) {
    const slices = all.filter((s) => s.release === r);
    const mine = slices.filter((s) => s.explicit);
    const R = [`# Release ${r}`, '', HEADER(CMD), ''];
    R.push(`${slices.length} slices in ${r}: ${mine.length} migrated, ${slices.length - mine.length} not migrated.`, '');

    R.push('## Migrated slices', '');
    if (mine.length) {
      R.push('| Slice | Module | Extends | Depends on | Design | Criteria |', '| --- | --- | --- | --- | --- | ---: |');
      for (const s of mine) R.push(`| ${sliceLink(s, outDir)} | ${list(s.links.modules)} | ${list(s.links.extends)} | ${list(s.links.depends)} | ${list(s.links.design)} | ${s.criteria} |`);
    } else R.push('None yet.');
    R.push('');

    // Graph nodes: migrated slices of this release plus the slices of this release they depend on.
    const nodes = new Set(mine.map((s) => s.sid));
    for (const s of mine) for (const t of s.links.depends) if (model.slices.get(t)?.release === r) nodes.add(t);
    let grew = true;
    while (grew) {
      grew = false;
      for (const sid of [...nodes]) {
        for (const t of model.slices.get(sid)?.links.depends ?? []) {
          if (model.slices.get(t)?.release === r && !nodes.has(t)) {
            nodes.add(t);
            grew = true;
          }
        }
      }
    }
    const earlier = new Set();
    for (const sid of nodes) for (const t of model.slices.get(sid)?.links.depends ?? []) if (model.slices.has(t) && model.slices.get(t).release !== r) earlier.add(t);
    for (const sid of nodes) for (const t of model.slices.get(sid)?.links.extends ?? []) if (model.slices.has(t)) earlier.add(t);

    R.push('## Dependency graph', '');
    if (nodes.size) {
      R.push('Arrows point from a slice to what it needs. Dashed arrows: «Розширює» (the same requirement in the previous release). Grey: not migrated yet, own dependencies unknown.', '');
      R.push('```mermaid', 'flowchart LR');
      const sortedNodes = [...nodes].sort();
      for (const sid of sortedNodes) R.push(`  ${nodeId(sid)}["${sid}"]`);
      if (earlier.size) {
        R.push('  subgraph earlier["Earlier releases"]');
        for (const sid of [...earlier].sort()) R.push(`    ${nodeId(sid)}["${sid}"]`);
        R.push('  end');
      }
      for (const sid of sortedNodes) {
        const s = model.slices.get(sid);
        for (const t of [...s.links.depends].sort()) if (model.slices.has(t)) R.push(`  ${nodeId(sid)} --> ${nodeId(t)}`);
        for (const t of s.links.extends) if (model.slices.has(t)) R.push(`  ${nodeId(sid)} -.-> ${nodeId(t)}`);
      }
      const grey = [...nodes, ...earlier].filter((sid) => !model.slices.get(sid).explicit).sort();
      if (grey.length) {
        R.push('  classDef notMigrated fill:#eee,stroke:#999,color:#555');
        R.push(`  class ${grey.map(nodeId).join(',')} notMigrated`);
      }
      R.push('```');
    } else R.push('No migrated slices in this release yet.');
    R.push('');

    R.push('## Build sequence', '');
    const { waves, cyclic } = buildWaves([...nodes].sort(), model);
    if (waves.length) {
      R.push('Topological order of the graph above, grouped into waves: every slice of a wave needs only slices of earlier waves or earlier releases, so slices of one wave can be built in parallel.', '');
      waves.forEach((w, i) => {
        R.push(`${i + 1}. **Wave ${i + 1}:** ${w.map((sid) => `${sid}${model.slices.get(sid).explicit ? '' : ' (не мігровано)'}`).join(', ')}`);
      });
      R.push('');
    } else R.push('No migrated slices in this release yet.', '');
    if (cyclic.length) R.push(`**Cycle — cannot be ordered:** ${cyclic.join(', ')}`, '');
    const rest = slices.filter((s) => !s.explicit && !nodes.has(s.sid));
    R.push('### Not migrated, not placed', '');
    if (rest.length) {
      R.push(`${rest.length} slices whose dependencies are unknown until their requirement is migrated:`, '');
      const byArea = new Map();
      for (const s of rest) {
        const k = s.feature.area;
        if (!byArea.has(k)) byArea.set(k, []);
        byArea.get(k).push(s.id);
      }
      for (const [area, ids] of byArea) R.push(`- ${area}: ${ids.join(', ')}`);
    } else R.push('None.');
    R.push('');
    files.set(`release-${RELEASE_KEY[r]}.md`, R.join('\n'));
  }

  // Coverage.
  const C = ['# Coverage', '', HEADER(CMD), ''];
  C.push('Per release: screens of the screen map without a slice that links them, migrated slices without design, and slices without acceptance criteria. A screen\'s release is the «Реліз» column of `docs/ux/screen-map.md`; a screen counts as covered when a slice of that release or an earlier one names it in «Дизайн».', '');
  const screens = registries.screens ? [...registries.screens.values()] : [];
  for (const r of SLICE_RELEASES) {
    C.push(`## ${r}`, '');
    const upto = explicit.filter((s) => releaseIndex(s.release) <= releaseIndex(r));
    const covered = new Set(upto.flatMap((s) => s.links.design));
    const relScreens = screens.filter((sc) => sc.release === r);
    const uncovered = relScreens.filter((sc) => !covered.has(sc.id));
    C.push(`### Screens without a slice (${uncovered.length} of ${relScreens.length})`, '');
    if (uncovered.length) {
      C.push('| Screen | Title | Requirements in the screen map | Waiting for |', '| --- | --- | --- | --- |');
      for (const sc of uncovered) {
        const reqs = sc.requirements.filter((id) => model.features.has(id));
        const pending = reqs.filter((id) => !model.features.get(id).card);
        const why = !reqs.length ? 'no requirement' : pending.length ? 'migration' : 'a «Дизайн» link';
        C.push(`| ${sc.id} | ${esc(sc.title.length > 90 ? `${sc.title.slice(0, 90)}…` : sc.title)} | ${list(sc.requirements)} | ${why} |`);
      }
    } else C.push('None.');
    C.push('');
    const rel = all.filter((s) => s.release === r);
    const noDesign = rel.filter((s) => s.explicit && !s.links.design.length);
    C.push(`### Migrated slices without design (${noDesign.length})`, '');
    C.push(noDesign.length ? noDesign.map((s) => `- ${s.sid}`).join('\n') : 'None.');
    C.push('');
    const noCrit = rel.filter((s) => s.criteria === 0);
    C.push(`### Slices without acceptance criteria (${noCrit.length})`, '');
    C.push(noCrit.length ? noCrit.map((s) => `- ${s.sid}${s.explicit ? '' : ' (не мігровано)'}`).join('\n') : 'None.');
    C.push('');
    const nm = rel.filter((s) => !s.explicit).length;
    C.push(`Not migrated in ${r}: ${nm} slices without design links (links are unknown until migration).`, '');
  }
  files.set('coverage.md', C.join('\n'));
  return files;
}
