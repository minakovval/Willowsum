// Markdown report.
import { CHECKS, CHECK_TITLES } from './findings.mjs';
import { RELEASES } from './config.mjs';

const esc = (s) => String(s).replace(/\|/g, '\\|').replace(/\r?\n/g, ' ');

/**
 * @param {object} p
 * @param {ReturnType<import('./corpus.mjs').buildCorpus>} p.corpus
 * @param {ReturnType<import('./run.mjs').runChecks>} p.result
 * @param {import('./findings.mjs').Finding[]} p.findings  findings with `baselined` applied
 * @param {string[]} p.stale
 * @param {number} p.baselineSize
 * @param {{competing?: object[]}} p.factsSpec
 * @param {string} p.command
 */
export function renderReport({ corpus, result, findings, stale, baselineSize, factsSpec, command }) {
  const L = [];
  const reqs = corpus.docs.filter((d) => d.kind === 'requirement');
  const errors = findings.filter((f) => f.severity === 'error' && !f.baselined);
  const baselined = findings.filter((f) => f.baselined);
  const warnings = findings.filter((f) => f.severity === 'warning');

  L.push('# Requirements check report', '');
  L.push(`Generated by \`${command}\` (tools/req-check). Do not edit by hand; rerun the command.`, '');
  L.push(`Scope: \`${corpus.prefix}/\` — ${reqs.length} requirement files in ${corpus.folders.length} module folders, plus 00-general.md and the READMEs.`, '');
  L.push(`**Result: ${errors.length ? 'FAIL' : 'PASS'}** — ${errors.length} new errors, ${baselined.length} baselined errors (reported as warnings), ${warnings.length} warnings. Baseline size: ${baselineSize} entries${stale.length ? `, ${stale.length} stale (fixed — remove them from baseline.json)` : ''}.`, '');

  // Summary by check.
  L.push('## Findings by check', '');
  L.push('| Check | New errors | Baselined errors | Warnings | Rules |', '| --- | ---: | ---: | ---: | --- |');
  for (const c of CHECKS) {
    const fs = findings.filter((f) => f.check === c);
    const rules = new Map();
    for (const f of fs) rules.set(f.rule, (rules.get(f.rule) ?? 0) + 1);
    L.push(`| ${CHECK_TITLES[c]} | ${fs.filter((f) => f.severity === 'error' && !f.baselined).length} | ${fs.filter((f) => f.baselined).length} | ${fs.filter((f) => f.severity === 'warning').length} | ${[...rules].map(([r, n]) => `${r} ${n}`).join(', ') || '—'} |`);
  }
  L.push('');

  // Counts per module and release.
  const cols = [...RELEASES.slice().sort((a, b) => order(a) - order(b)), 'invalid', 'n/a'];
  L.push('## Requirements per module and release', '');
  L.push('Main release = first release named on the «Реліз» line.', '');
  L.push(`| Module | Files | ${cols.join(' | ')} |`, `| --- | ---: | ${cols.map(() => '---:').join(' | ')} |`);
  const totals = new Map(cols.map((c) => [c, 0]));
  for (const folder of corpus.folders) {
    const docs = reqs.filter((d) => d.folder === folder);
    const counts = new Map(cols.map((c) => [c, 0]));
    for (const d of docs) {
      const r = result.release.releaseOf.get(d.rel) ?? 'n/a';
      counts.set(r, counts.get(r) + 1);
      totals.set(r, totals.get(r) + 1);
    }
    L.push(`| ${folder.toUpperCase()} | ${docs.length} | ${cols.map((c) => counts.get(c) || '').join(' | ')} |`);
  }
  L.push(`| **Total** | **${reqs.length}** | ${cols.map((c) => `**${totals.get(c)}**`).join(' | ')} |`, '');

  // Exemptions.
  L.push('## Release/priority exemptions', '');
  L.push('A folder must carry the field when at least half of its files have it; a single file is exempt when its README row leaves the cell empty.', '');
  const exR = result.release.folders.filter((f) => !f.needRelease);
  const exP = result.release.folders.filter((f) => !f.needPriority);
  L.push(`- Folders exempt from the release line: ${exR.map((f) => `\`${f.folder}/\` (${f.withRelease}/${f.files})`).join(', ') || 'none'}.`);
  L.push(`- Folders exempt from the priority: ${exP.map((f) => `\`${f.folder}/\` (${f.withPriority}/${f.files})`).join(', ') || 'none'}.`);
  const exF = result.release.exemptFiles;
  L.push(`- Files exempt by README: ${exF.map((e) => `\`${e.file.split('/').pop()}\` (${e.field})`).join(', ') || 'none'}.`, '');

  // Acceptance criteria stats.
  L.push('## Acceptance criteria', '');
  const without = [...result.criteria.without].map(([f, n]) => `\`${f}/\` ${n}`).join(', ');
  L.push(`${result.criteria.sections} files have a «Критерії приймання» section with ${result.criteria.criteria} numbered criteria, all checked for the Given/When/Then form and continuous numbering.${without ? ` Files without the section (criteria tables or narrative only): ${without}.` : ''}`, '');

  // Fact registry.
  L.push('## Fact registry', '');
  L.push('Facts and patterns: `tools/req-check/facts.json`. "Mentions" counts every value the patterns matched.', '');
  L.push('| Fact | Canonical | Mentions | Mismatches | Values seen |', '| --- | --- | ---: | ---: | --- |');
  for (const f of result.facts.facts) {
    const s = result.facts.stats.get(f.id);
    const canon = f.type === 'plan' ? Object.entries(f.allowed).map(([k, v]) => `${k} ${v}`).join(', ') : f.allowed.join(' / ');
    const vals = [...s.values].sort((a, b) => b[1] - a[1]).map(([v, n]) => `${v} ×${n}`).join(', ');
    L.push(`| ${esc(f.title)} (\`${f.id}\`) | ${esc(canon)} | ${s.mentions} | ${s.mismatches} | ${esc(vals) || '—'} |`);
  }
  L.push('');
  if (factsSpec.competing?.length) {
    L.push('### Competing values found while building the registry', '');
    for (const c of factsSpec.competing) L.push(`- **${c.fact}**: ${c.note}`);
    L.push('');
  }

  // Findings.
  const list = (title, items, note) => {
    L.push(`## ${title} (${items.length})`, '');
    if (note) L.push(note, '');
    if (!items.length) {
      L.push('None.', '');
      return;
    }
    L.push('| File:line | Rule | Message |', '| --- | --- | --- |');
    for (const f of items) L.push(`| \`${f.file.replace(`${corpus.prefix}/`, '')}:${f.line}\` | ${f.rule} | ${esc(f.message)} |`);
    L.push('');
  };
  list('New errors', errors, 'These fail CI. Fix the requirement file (with the owner\'s decision) or, if the checker is wrong, fix the checker.');
  list('Baselined errors', baselined, 'Known when the checker was introduced (tools/req-check/baseline.json). Each needs an owner decision; remove the entry once fixed.');
  list('Warnings', warnings);
  if (stale.length) {
    L.push(`## Stale baseline entries (${stale.length})`, '', ...stale.map((s) => `- \`${s}\``), '');
  }

  // Files with warnings.
  const byFile = new Map();
  for (const f of [...baselined, ...warnings]) byFile.set(f.file, (byFile.get(f.file) ?? 0) + 1);
  L.push(`## Files with warnings (${byFile.size})`, '');
  L.push('Includes baselined errors.', '');
  if (byFile.size) {
    L.push('| File | Warnings |', '| --- | ---: |');
    for (const [file, n] of [...byFile].sort((a, b) => (a[0] < b[0] ? -1 : 1))) L.push(`| \`${file.replace(`${corpus.prefix}/`, '')}\` | ${n} |`);
  } else L.push('None.');
  L.push('');
  return L.join('\n');
}

function order(r) {
  return ['MVP', 'Сейф', 'v1-mobile', 'v1', 'v2'].indexOf(r);
}
